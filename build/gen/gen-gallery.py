import json, io, os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC  = os.path.join(ROOT, "ayvede-site", "docs", "gallery-reference", "gallery_data.json")
d = json.load(io.open(SRC, encoding="utf8"))

# Deterministic motif-family assignment, one char per framework 1..50.
# Index into GAL_FAMS: 0 cycle 1 steps 2 ladder 3 funnel 4 network 5 bridge
# 6 exchange 7 balance 8 compass 9 matrix a systemMap b orbit c path d stack e tree
FAM = "207169cb8d540a0e193c2470b212a31c279033a0dec062402b"
assert len(FAM) == 50, len(FAM)

def js(s):
    return json.dumps(s, ensure_ascii=False)

cats = sorted(d["categories"].items(), key=lambda kv: kv[1]["order"])
out = []
out.append("const GAL_FAMS = [\"cycle\",\"steps\",\"ladder\",\"funnel\",\"network\",\"bridge\",\"exchange\",\"balance\",\"compass\",\"matrix\",\"systemMap\",\"orbit\",\"path\",\"stack\",\"tree\"];")
out.append("//  One char per framework 1..50, indexing GAL_FAMS. Fixed, so a given")
out.append("//  framework always renders the same family. Never randomised at render.")
out.append("const GAL_FAM_MAP = " + js(FAM) + ";")
out.append("const GAL_CATS = [")
for cid, c in cats:
    out.append("  { id: %s, name: %s, short: %s, description: %s, order: %d }," % (
        js(cid), js(c["name"]), js(c["short"]), js(c["description"]), c["order"]))
out.append("];")
out.append("//  Keys: t title, a author, c category, w what, q quick, k chips. Values are\n//  rendered verbatim from docs/gallery-reference/gallery_data.json")
out.append("//  (sha256 c7756ca5...). Generated by site-build/gen/gen-gallery.py; do not")
out.append("//  hand-edit the strings here, regenerate instead.")
out.append("const GAL_ITEMS = [")
for it in sorted(d["items"], key=lambda x: x["n"]):
    out.append("  { n: %d, t: %s, a: %s, c: %s, w: %s, q: %s, k: [%s] }," % (
        it["n"], js(it["title"]), js(it["author"]), js(it["category"]),
        js(it["what"]), js(it["quick"]), ",".join(js(c) for c in it["chips"])))
out.append("];")
block = "\n".join(out) + "\n"
io.open(os.path.join(ROOT, "site-build", "gen", "gallery-data-block.js"), "w", encoding="utf8").write(block)
print("data block bytes:", len(block.encode("utf8")))

# public manifest
FAMS = ["cycle","steps","ladder","funnel","network","bridge","exchange","balance","compass","matrix","systemMap","orbit","path","stack","tree"]
BASIS = {
 "cycle":"closed loop of the framework chips","steps":"ordered ascending stages from the chips",
 "ladder":"vertical progression of the chips","funnel":"narrowing selection across the chips",
 "network":"peer nodes and relations between chips","bridge":"two anchors joined by a span",
 "exchange":"two opposed columns with crossing paths","balance":"fulcrum weighing the chips",
 "compass":"four-axis orientation of the chips","matrix":"two-by-two quadrants from the chips",
 "systemMap":"central node with feedback loops","orbit":"concentric rings with chip satellites",
 "path":"waypoint route through the chips","stack":"layered slabs, one per chip",
 "tree":"branching decision from the chips"}
rows = ["number,title,author,category_id,category_name,anchor,motif_family,motif_basis,content_source,visual_rendering,third_party_images,third_party_logos,headway_assets,public_publish_status"]
def q(s):
    s = str(s)
    return '"' + s.replace('"','""') + '"' if any(ch in s for ch in ',"\n') else s
cmap = {cid: c["name"] for cid, c in d["categories"].items()}
for it in sorted(d["items"], key=lambda x: x["n"]):
    fam = FAMS[int(FAM[it["n"]-1], 16)]
    rows.append(",".join(q(v) for v in [
        it["n"], it["title"], it["author"], it["category"], cmap[it["category"]],
        "gallery-i-%02d" % it["n"], fam, BASIS[fam],
        "Ayvede original editorial summary",
        "Original procedural React/SVG visual generated from framework chips",
        "none","none","removed","original-content-only build"]))
man = "\n".join(rows) + "\n"
io.open(os.path.join(ROOT, "ayvede-site", "docs", "gallery-visual-manifest.csv"), "w", encoding="utf8").write(man)
print("manifest bytes:", len(man.encode("utf8")), "rows:", len(rows)-1)
